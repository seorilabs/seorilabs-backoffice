import assert from 'node:assert/strict';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
import { mutateConsoleRuntime, readConsoleRuntimeState, consoleRuntimeLedger } from '../src/lib/control-plane/console-oauth-runtime';
import { ConsoleOAuth } from '../src/lib/analytics/console-sync/oauth';
import { withConsoleCollectionLock } from '../src/lib/analytics/console-sync/collect';
import { prisma } from '../src/lib/prisma';
const url = new URL(process.env.DATABASE_URL ?? '');
if (url.hostname !== '127.0.0.1' || url.port !== '33319' || url.pathname !== '/backoffice_console_runtime_qa')
    throw Error('ISOLATED_DATABASE_REQUIRED');
const version = (n: number) => `local/versions/00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
async function main() {
    process.env.AIT_CONSOLE_RUNTIME_PRINCIPAL = 'qa:console-metrics-collector';
    const admin = { kind: 'user' as const, login: 'qa-console-admin' }, viewer = { kind: 'user' as const, login: 'qa-console-viewer' };
    const worker = { kind: 'worker' as const, principal: 'qa:console-metrics-collector', workspaceId: 38345 as const };
    await prisma.user.createMany({ data: [{ githubId: 99999101n, login: admin.login, role: 'ADMIN', allowlisted: true }, { githubId: 99999102n, login: viewer.login, role: 'VIEWER', allowlisted: true }] });
    const register = { operation: 'REGISTER' as const, workspaceId: 38345 as const, expected: null, secretVersion: version(1) };
    await assert.rejects(mutateConsoleRuntime(register, viewer, randomUUID()), /OAUTH_RUNTIME_ACCESS_FORBIDDEN/);
    await assert.rejects(mutateConsoleRuntime(register, worker, randomUUID()), /OAUTH_RUNTIME_ACCESS_FORBIDDEN/);
    await assert.rejects(mutateConsoleRuntime({ ...register, refreshToken: 'synthetic-secret' } as never, admin, randomUUID()), /OAUTH_RUNTIME_REQUEST_INVALID/);
    const initial = (await mutateConsoleRuntime(register, admin, randomUUID())).state;
    const attemptId = randomUUID(), requestId = `${attemptId}:begin`;
    const begin = { operation: 'BEGIN' as const, workspaceId: 38345 as const, expected: initial, attemptId };
    const flight = await mutateConsoleRuntime(begin, worker, requestId);
    assert.equal(flight.state.phase, 'REFRESH_IN_FLIGHT');
    assert.equal((await mutateConsoleRuntime(begin, worker, requestId)).duplicate, true);
    await assert.rejects(mutateConsoleRuntime({ ...begin, attemptId: randomUUID() }, worker, requestId), /OAUTH_IDEMPOTENCY_CONFLICT/);
    await assert.rejects(mutateConsoleRuntime({ ...begin, attemptId: randomUUID() }, worker, randomUUID()), /OAUTH_STATE_CONFLICT/);
    const fresh = new PrismaClient();
    assert.equal((await readConsoleRuntimeState(fresh)).phase, 'REFRESH_IN_FLIGHT');
    await fresh.$disconnect();
    let grantReads = 0, providerCalls = 0;
    await withConsoleCollectionLock(async (assertHeld) => assert.rejects(ConsoleOAuth.open({ read: async () => { grantReads++; throw Error('MUST_NOT_READ_OLD_GRANT'); }, add: async () => { throw Error('MUST_NOT_ADD'); } }, consoleRuntimeLedger(worker, assertHeld), async () => { providerCalls++; throw Error('MUST_NOT_REFRESH'); }), /OAUTH_REFRESH_IN_FLIGHT/));
    assert.equal(grantReads, 0);
    assert.equal(providerCalls, 0);
    const completed = (await mutateConsoleRuntime({ operation: 'COMPLETE', workspaceId: 38345, expected: flight.state, secretVersion: version(2) }, worker, randomUUID())).state;
    assert.equal(completed.generation, 2);
    const concurrent = await Promise.allSettled([1, 2].map(() => mutateConsoleRuntime({ operation: 'BEGIN', workspaceId: 38345, expected: completed, attemptId: randomUUID() }, worker, randomUUID())));
    assert.equal(concurrent.filter(r => r.status === 'fulfilled').length, 1);
    const stuck = await readConsoleRuntimeState();
    assert.equal(stuck.phase, 'REFRESH_IN_FLIGHT');
    await assert.rejects(mutateConsoleRuntime({ operation: 'REGISTER', workspaceId: 38345, expected: stuck, secretVersion: version(3) }, worker, randomUUID()), /OAUTH_RUNTIME_ACCESS_FORBIDDEN/);
    const recovered = (await mutateConsoleRuntime({ operation: 'REGISTER', workspaceId: 38345, expected: stuck, secretVersion: version(3) }, admin, randomUUID())).state;
    assert.equal(recovered.generation, 3);
    const audits = await prisma.auditLog.findMany({ where: { entityType: 'ConsoleOAuthRuntimeState' } });
    assert.equal(audits.length, 5);
    assert.ok(!JSON.stringify(audits).includes('synthetic-secret'));
    assert.ok(audits.every(a => a.payload && Object.keys(a.payload).every(k => !['accessToken', 'refreshToken'].includes(k))));
    assert.equal(await prisma.credentialBinding.count(), 0);
    assert.equal(await prisma.configRevision.count(), 0);
    console.log('격리 MySQL runtime: 권한·고정 범위·CAS 경합·멱등·append-only 감사·새 연결 IN_FLIGHT 차단·catalog/설정 비변경 통과');
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => prisma.$disconnect());
