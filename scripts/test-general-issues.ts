import assert from "node:assert/strict";
import "./qa/general-issue-boundaries.cjs";
import { prisma } from "@/lib/prisma";
import { createGeneralIssueDraftCore, editGeneralIssueDraftCore, discardGeneralIssueDraftCore } from "@/lib/core/general-issues";
import { commitDraftCore, confirmDraftRegistrationCore, createPlanningDraftCore, createBugDraftCore } from "@/lib/core/ai-drafts";
import { handleOperatorInteraction } from "@/lib/operator/handler";
import { createOperatorCommand, processNextOperatorCommand } from "@/lib/operator/command-runs";
import type { OperatorInteraction } from "@/lib/operator/types";
import { normalizeSlackRequest } from "@/lib/slack/normalize";
import { env } from "@/lib/env";

type QaState = { mode: string; writes: number; slackUsers: Record<string, { id: string; team_id: string; deleted: boolean; is_bot: boolean }>; messages: unknown[]; issues: unknown[] };
const state = (globalThis as unknown as { __generalIssueQa: QaState }).__generalIssueQa;
async function main() {
  const suffix = Date.now().toString();
  const app = await prisma.app.create({ data: { slug: `qa-${suffix}`, displayName: "격리 검수 앱", repoFullName: `seorilabs/qa-general-${suffix}`, type: "APP", engine: "RN", marketTargets: [] } });
  const owner = await prisma.user.create({ data: { login: `qa-${suffix}`, githubId: BigInt(suffix), role: "MAINTAINER", allowlisted: true } });
  await prisma.appOwner.create({ data: { appId: app.id, userId: owner.id } });
  const actor = { actorLabel: `@${owner.login}` };
  const create = () => createGeneralIssueDraftCore({ ...actor, appId: app.id, request: "설정 화면의 알림 설정 방법을 조사해 주세요." });
  const first = await create();
  assert.equal(first.kind, "GENERAL_ISSUE");
  await assert.rejects(editGeneralIssueDraftCore({ ...actor, draftId: first.id, title: "x".repeat(121), body: "본문", version: first.updatedAt.toISOString() }));
  const edited = await editGeneralIssueDraftCore({ ...actor, draftId: first.id, title: "수정한 요청", body: "수정한 본문", version: first.updatedAt.toISOString() });
  await assert.rejects(editGeneralIssueDraftCore({ ...actor, draftId: first.id, title: "낡은 요청", body: "본문", version: first.updatedAt.toISOString() }));
  const duplicate = await Promise.allSettled([commitDraftCore({ ...actor, draftId: first.id }), commitDraftCore({ ...actor, draftId: first.id })]);
  assert.ok(duplicate.some(r => r.status === "fulfilled"), duplicate.map(r => r.status === "rejected" ? String(r.reason) : "ok").join("\n"));
  assert.equal(state.writes, 1);
  const storedIssue = await prisma.issueMirror.findFirstOrThrow({ where: { appId: app.id } });
  assert.equal(storedIssue.title, edited.title);
  assert.deepEqual(storedIssue.labels, []);
  assert.equal((await prisma.app.findUniqueOrThrow({ where: { id: app.id } })).currentStage, "PLANNING");
  assert.equal(await prisma.agentRun.count({ where: { appId: app.id } }), 0);
  assert.equal(await prisma.releaseRecord.count({ where: { appId: app.id } }), 0);
  assert.equal((await commitDraftCore({ ...actor, draftId: first.id })).issueNumber, storedIssue.number);
  const unknown = await create();
  state.mode = "github-unknown";
  await assert.rejects(commitDraftCore({ ...actor, draftId: unknown.id }));
  state.mode = "ok";
  await assert.rejects(commitDraftCore({ ...actor, draftId: unknown.id }));
  assert.equal(state.writes, 2);
  assert.equal((await confirmDraftRegistrationCore(unknown.id, actor.actorLabel)).confirmed, true);
  assert.equal(await prisma.issueMirror.count({ where: { appId: app.id } }), 2);
  const denied = await create();
  state.mode = "github-denied";
  await assert.rejects(commitDraftCore({ ...actor, draftId: denied.id }));
  assert.equal((await prisma.aiDraft.findUniqueOrThrow({ where: { id: denied.id } })).claimedAt, null);
  state.mode = "ok";
  await discardGeneralIssueDraftCore(denied.id, actor);
  await assert.rejects(commitDraftCore({ ...actor, draftId: denied.id }));
  await assert.rejects(commitDraftCore({ actorLabel: "@someone-else", draftId: first.id }));
  const revoked = await create();
  await prisma.appOwner.delete({ where: { appId_userId: { appId: app.id, userId: owner.id } } });
  await assert.rejects(commitDraftCore({ ...actor, draftId: revoked.id }), /권한/);
  await prisma.appOwner.create({ data: { appId: app.id, userId: owner.id } });
  process.env.FEATURE_GENERAL_ISSUES_ENABLED = "false";
  await assert.rejects(create(), /비활성/);
  await assert.rejects(commitDraftCore({ ...actor, draftId: revoked.id }), /비활성/);
  process.env.FEATURE_GENERAL_ISSUES_ENABLED = "true";
  state.mode = "claude-fail";
  const before = await prisma.aiDraft.count();
  await assert.rejects(create());
  assert.equal(await prisma.aiDraft.count(), before);
  state.mode = "ok";
  const slackUserId = `U${suffix}`;
  state.slackUsers[slackUserId] = { id: slackUserId, team_id: "T000GENERAL", deleted: false, is_bot: false };
  process.env.SLACK_ROLE_PRODUCT_USERS = slackUserId;
  await prisma.slackAccountLink.create({ data: { githubId: owner.githubId, slackUserId } });
  const slackActor = { actorLabel: `slack:${slackUserId}`, expectedGithubId: String(owner.githubId) };
  const draft = await createGeneralIssueDraftCore({ ...slackActor, appId: app.id, request: "설정 조사" });
  const writesBeforeRevocation = state.writes;
  state.slackUsers[slackUserId].deleted = true;
  await assert.rejects(commitDraftCore({ ...slackActor, draftId: draft.id }), /Slack 사용자/);
  state.slackUsers[slackUserId].deleted = false;
  state.slackUsers[slackUserId].team_id = "T000OTHER";
  await assert.rejects(commitDraftCore({ ...slackActor, draftId: draft.id }), /Slack 사용자/);
  state.slackUsers[slackUserId].team_id = "T000GENERAL";
  state.slackUsers[slackUserId].is_bot = true;
  await assert.rejects(commitDraftCore({ ...slackActor, draftId: draft.id }), /Slack 사용자/);
  state.slackUsers[slackUserId].is_bot = false;
  process.env.SLACK_ROLE_PRODUCT_USERS = "";
  process.env.SLACK_ROLE_VIEWER_USERS = slackUserId;
  await assert.rejects(commitDraftCore({ ...slackActor, draftId: draft.id }), /역할/);
  process.env.SLACK_ROLE_VIEWER_USERS = "";
  process.env.SLACK_ROLE_PRODUCT_USERS = slackUserId;
  await prisma.slackAccountLink.delete({ where: { slackUserId } });
  await assert.rejects(commitDraftCore({ ...slackActor, draftId: draft.id }), /연결/);
  assert.equal(state.writes, writesBeforeRevocation, "Slack 권한과 연결 검증 실패는 GitHub 쓰기 전에 중단한다");
  await prisma.slackAccountLink.create({ data: { githubId: owner.githubId, slackUserId } });
  const slashBody = new URLSearchParams({ command: "/seori", text: `issue create app:${app.slug}`, api_app_id: "A000GENERAL", team_id: "T000GENERAL", channel_id: "C000OPS", user_id: slackUserId, user_name: "qa-operator", trigger_id: `qa-trigger-${suffix}` });
  const normalized = normalizeSlackRequest(slashBody.toString(), env.operatorRoles);
  const interaction: OperatorInteraction = normalized.interaction;
  assert.equal(interaction.applicationId, "A000GENERAL");
  assert.equal(interaction.workspaceId, "T000GENERAL");
  assert.equal(interaction.channelId, "C000OPS");
  assert.equal(interaction.actor?.id, slackUserId);
  assert.deepEqual(interaction.actor?.roles, ["product"]);
  const modal = await handleOperatorInteraction(interaction);
  assert.equal(modal.type, 9);
  assert.match(JSON.stringify(modal), /modal:general/);
  assert.equal((await handleOperatorInteraction({ ...interaction, channelId: "C000RELEASE" })).type, 4);
  assert.match(JSON.stringify(await handleOperatorInteraction({ ...interaction, data: { name: "unknown" } })), /지원하지/);
  const auto = await handleOperatorInteraction({ ...interaction, type: 4, data: { name: "issue create", options: [{ type: 3, name: "app", focused: true, value: app.slug }] } });
  assert.equal(auto.type, 8);
  assert.match(JSON.stringify(auto), new RegExp(app.slug));
  const run = await createOperatorCommand({ sourceInteractionId: `qa-run-${suffix}`, appId: app.id, operation: "general_generate", actorUserId: slackUserId, channelId: "C000OPS", params: { text: "보존할 요청", githubId: String(owner.githubId) } });
  assert.equal(run.sourceProvider, "SLACK");
  state.mode = "claude-fail";
  await processNextOperatorCommand();
  const failed = await prisma.operatorCommandRun.findUniqueOrThrow({ where: { id: run.id } });
  assert.equal(failed.status, "FAILED");
  assert.equal((failed.params as { text: string }).text, "보존할 요청");
  state.mode = "ok";
  const planning = await createPlanningDraftCore({ appId: app.id, idea: "격리 기획", actorLabel: actor.actorLabel });
  const bug = await createBugDraftCore({ appId: app.id, symptom: "격리 버그", actorLabel: actor.actorLabel });
  assert.ok(planning.outputText);
  assert.ok(bug.outputText);
  assert.equal(await prisma.aiDraft.count({ where: { appId: app.id, kind: { in: ["PLANNING_SPEC", "BUG_REPORT"] } } }), 2);
  assert.ok(await prisma.auditLog.count({ where: { action: "ai.general_issue_committed" } }));
  console.log("PASS: 일반 이슈 실제 MySQL·Claude 경계·GitHub 등록/미러·중복·불명확/재조회·거절·취소·낡은 편집·권한회수·역할회수·연결해제·플래그·실패입력보존·Slack /seori 입력/자동완성·기획/버그 회귀");
}
main().finally(() => prisma.$disconnect()).catch(error => { console.error(error); process.exitCode = 1; });
